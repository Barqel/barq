/**
 * The single place an application declares itself: routes + registries
 * (jobs / listeners / commands) + optional overrides. Everything else has
 * sensible defaults.
 */
export interface BarqConfig {
	/** Shown in logs, the root route and the CLI (default: "Barq App"). */
	name?: string;
	/** Registers all HTTP routes — usually `registerApi` from `app/routes/api.ts`. */
	routes?: (app: App) => void;
	/** Scheduled jobs — starts with the server, generated by `job:make`. */
	jobs?: import("../auto-register/types").JobsSetting;
	/** Event listeners — generated by `listener:make`. */
	listeners?: import("../auto-register/types").ListenersSetting;
	/** Console commands — generated by `command:make`. */
	commands?: import("../auto-register/types").CommandsSetting;
	/** Application messages per locale; merged over the framework defaults. */
	translations?: import("../auto-register/types").TranslationsSetting;
	/** Locale defaults and supported list (inferred when omitted). */
	locales?: LocalesConfig;
	/** OpenAPI docs title/version/paths/UI overrides. */
	openapi?: AppOpenApiConfig;
	/** Mail (SMTP host, sender, retries) — see the `MAIL_*` env variables. */
	email?: AppEmailConfig;
	/** Static files options (serves `public/` when it exists). */
	static?: AppStaticConfig;
	/** Serve `GET /health` (default: true). */
	health?: boolean;
	/** Serve `GET /` with app pointers (default: true). */
	root?: boolean;
	/**
	 * Escape hatch, called after the core plugins but before routes:
	 * register extra plugins (auth, upload, …) or global middleware.
	 */
	configure?: (app: App) => void;
	/** Auto-register configuration for automatic file discovery. */
	autoRegister?: import("../auto-register/types").AutoRegisterConfig;
}

/** Identity helper for `barq.config.ts` — gives full typing in one line. */
export function defineConfig(config: BarqConfig): BarqConfig {
	return config;
}

export interface CreateAppOptions {
	/**
	 * Register scheduled jobs and start their timers.
	 * Defaults to `false` while testing (`NODE_ENV=test` — `bun test` sets
	 * it) so tests never run background work, and `true` everywhere else.
	 */
	jobs?: boolean;
}

/** Builds the fully-wired application. Never listens. */
export function createApp(
	config: BarqConfig = {},
	options: CreateAppOptions = {},
): App {
	const production = env.APP_ENV === ENV.PRODUCTION;
	const openapiConfig = resolveOpenApi(config.openapi);
	const name = config.name ?? "Barq App";

	setRuntimeInfo({
		name,
		env: env.APP_ENV,
		port: env.APP_PORT,
		docsPath: openapiConfig.docsPath,
		specPath: openapiConfig.specPath,
	});

	const app = new App({ development: !production, hostname: env.APP_HOST });

	// Request scope FIRST: everything below (logger, i18n, handlers, onError)
	// must execute inside the AsyncLocalStorage context born here.
	app.use(requestContextMiddleware);

	app.use(cors(corsOptions(env.APP_CORS_ORIGIN)));

	app.plugin(helmetPlugin());

	app.plugin(
		loggerPlugin({
			mode: "auto",
			level: env.LOG_LEVEL,
			skip: (ctx) => ctx.pathname === "/health",
		}),
	);

	app.plugin(
		compressPlugin({
			threshold: 1024,
			encodings: ["br", "gzip", "deflate"],
		}),
	);

	// The mailer — `app.mail`, the process-wide `mailer()` and the DI
	// container all point at the same instance. Without a configured SMTP
	// host the messages are logged instead of sent.
	const emailConfig = resolveEmail(config.email, env);

	app.plugin(emailPlugin(emailConfig));
	container.registerInstance(Mailer, app.mail);

	const rawTranslations = config.translations;
	const resolvedTranslations: TranslationsRecord =
		rawTranslations &&
		typeof rawTranslations === "object" &&
		"items" in rawTranslations
			? ((rawTranslations as { items?: TranslationsRecord }).items ?? {})
			: ((rawTranslations as TranslationsRecord) ?? {});

	app.plugin(
		i18nPlugin(
			resolveLocales({
				...config.locales,
				translations: resolvedTranslations,
			}),
		),
	);

	// Global rate limiting (after i18n so the 429 body is localized;
	// helmet/logger `after` hooks still run on rejected requests).
	app.plugin(globalRateLimiter);

	// Typed event bus (per-request copy at `ctx.state.events`) + listeners.
	app.plugin(
		eventsPlugin({
			wildcards: true,
			onError: (error, event) => {
				console.error(`[events] listener failed for ${event}:`, error);
			},
		}),
	);
	setEventBus(app.events);
	const rawListeners = config.listeners;
	const resolvedListeners: ListenerClass[] = Array.isArray(rawListeners)
		? rawListeners
		: (rawListeners?.items ?? []);
	registerListeners(app.events, resolvedListeners);

	app.plugin(openapi(openapiConfig));

	const storage = resolveStatic(config.static, production);

	if (storage.enabled && existsSync(PUBLIC_DIR)) {
		staticFiles({
			root: PUBLIC_DIR,
			prefix: storage.prefix,
			dotfiles: "ignore",
			index: "index.html",
			etag: true,
			maxAge: storage.maxAge,
			immutable: storage.immutable,
		})(app);
	}

	// Liveness probe for load balancers / Docker / PaaS.
	if (config.health !== false) {
		app.get("/health", () => {
			return json({
				success: true,
				status: "ok",
				env: env.APP_ENV,
				time: new Date().toISOString(),
			});
		});
	}

	// Root: quick pointers for whoever opens the base URL.
	if (config.root !== false) {
		app.get("/", () => {
			return json({
				name,
				version: openapiConfig.version,
				docs: openapiConfig.docsPath,
				spec: openapiConfig.specPath,
				health: "/health",
			});
		});
	}

	config.configure?.(app);
	config.routes?.(app);

	// Scheduled jobs LAST: every plugin, listener and route is wired before
	// any timer starts, so `runOnInit` jobs see a fully-booted application.
	app.plugin(cron());
	const startJobs = options.jobs ?? process.env.NODE_ENV !== "test";
	const rawJobs = config.jobs;
	const resolvedJobs: JobClass[] = Array.isArray(rawJobs)
		? rawJobs
		: (rawJobs?.items ?? []);
	registerJobs(app.cron, resolvedJobs, { autoStart: startJobs });

	app.onError((error, ctx) => {
		if (error instanceof HttpError) {
			return json(error.body, error.status);
		}

		if (!production) {
			console.error("Request failed:", error);
		} else {
			console.error("Request failed:", (error as Error)?.message ?? error);
		}

		return json(
			{
				success: false,
				message: ctx.t("errors.internal"),
			},
			500,
		);
	});

	app.notFound((ctx) => {
		return json(
			{
				success: false,
				message: ctx.t("errors.notFound"),
				path: ctx.pathname,
			},
			404,
		);
	});

	return app;
}

export interface StartOptions {
	/** See `CreateAppOptions.jobs`. */
	jobs?: boolean;
	/** Print the boot banner (default: true). */
	banner?: boolean;
	/** Install SIGINT/SIGTERM graceful-shutdown handlers (default: true). */
	signals?: boolean;
}

export interface BarqServer {
	app: App;
	port: number;
	stop: () => Promise<void>;
}

/**
 * Production entrypoint in one call: build → listen → banner → signals.
 *
 *   import { start } from "@barq";
 *   import config from "./barq.config";
 *   start(config);
 */
export function start(
	config: BarqConfig = {},
	options: StartOptions = {},
): BarqServer {
	const openapiConfig = resolveOpenApi(config.openapi);
	const app = createApp(config, { jobs: options.jobs });
	const server = app.listen(env.APP_PORT);
	const port = server.port ?? env.APP_PORT;

	if (options.banner !== false) {
		printBanner({
			env: env.APP_ENV,
			port,
			docsPath: openapiConfig.docsPath,
			specPath: openapiConfig.specPath,
		});
	}

	const stopWith = async (signal: string): Promise<void> => {
		console.log(`\nReceived ${signal}, shutting down gracefully...`);

		try {
			await shutdown(app);
			console.log("Server stopped.");
			process.exit(0);
		} catch (error) {
			console.error("Error during shutdown:", error);
			process.exit(1);
		}
	};

	const onSigint = (): void => void stopWith("SIGINT");
	const onSigterm = (): void => void stopWith("SIGTERM");
	const onRejection = (reason: unknown): void => {
		console.error("Unhandled rejection:", reason);
	};

	if (options.signals !== false) {
		process.on("SIGINT", onSigint);
		process.on("SIGTERM", onSigterm);
		process.on("unhandledRejection", onRejection);
	}

	return {
		app,
		port,
		stop: async () => {
			if (options.signals !== false) {
				process.off("SIGINT", onSigint);
				process.off("SIGTERM", onSigterm);
				process.off("unhandledRejection", onRejection);
			}

			await shutdown(app);
		},
	};
}

/**
 * Graceful shutdown: stop scheduled timers, release stores, then finish
 * in-flight requests (with a hard timeout).
 */
export async function shutdown(app: App, timeoutMs = 5_000): Promise<void> {
	app.cron.stopAll();
	idempotencyStore.destroy();
	await app.stop(timeoutMs);
}
