// Composition root of the framework: `createApp()` assembles the fully
// wired application (plugins, middleware, routes, listeners, jobs, error
// handling) from a small config object; `start()` boots it on a real port;
// `shutdown()` stops it gracefully.
//
// `createApp()` only ASSEMBLES the app — it never listens, prints or
// installs signal handlers. Tests (`createTestApp`) and the production
// entrypoint (`start`) both build on it, so tests exercise the exact same
// stack as production without booting a real port.
import { existsSync } from "node:fs";
import { App, cors, HttpError, json } from "@barqel/barq";
import { compressPlugin } from "@barqel/barq-compress";
import { cron } from "@barqel/barq-cron";
import { emailPlugin, Mailer } from "@barqel/barq-email";
import { eventsPlugin } from "@barqel/barq-events";
import { helmetPlugin } from "@barqel/barq-helmet";
import { i18nPlugin, type TranslationsRecord } from "@barqel/barq-i18n";
import { loggerPlugin } from "@barqel/barq-logger";
import { openapi } from "@barqel/barq-openapi";
import { staticFiles } from "@barqel/barq-static";
import { container } from "tsyringe";
import { corsOptions } from "../config/cors";
import { type AppEmailConfig, resolveEmail } from "../config/email";
import { idempotencyStore } from "../config/idempotency";
import { type LocalesConfig, resolveLocales } from "../config/locales";
import { type AppOpenApiConfig, resolveOpenApi } from "../config/openapi";
import { globalRateLimiter } from "../config/rate-limit";
