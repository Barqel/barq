/** The closest ASCII representation of a string. */
export function transliterate(value: string): string {
	// Drop the combining marks first ("é" → "e", "ü" → "u"), then map what
	// is left.
	const decomposed = value.normalize("NFD").replace(/\p{M}+/gu, "");
	let result = "";

	for (const character of decomposed) {
		const code = character.codePointAt(0) ?? 0;

		if (code < 0x80) {
			result += character;
			continue;
		}

		// Full-width ASCII forms.
		if (code >= 0xff01 && code <= 0xff5e) {
			result += String.fromCharCode(code - 0xfee0);
			continue;
		}

		result += TRANSLITERATIONS[character] ?? "";
	}

	return result;
}

/** The ASCII representation of a string, or the string itself when it is ASCII. */
export function ascii(value: string): string {
	// biome-ignore lint/suspicious/noControlCharactersInRegex: the ASCII range is the point
	return /^[\x00-\x7F]*$/u.test(value) ? value : transliterate(value);
}
